"""synth.py -- controlled ground-truth injection for the GNSS benchmark.

The three tasks need exact ground truth, which real series cannot provide, so
known signals and known power-law noise are injected:

    signal(t) = trend*(t-t0) + A1*sin(2pi(t-t0)) + A2*sin(4pi(t-t0)+phi)
                + steps + transients                       [mm]
    noise     = WN(sigma_wn) + FN(sigma_fn) + RW(sigma_rw) [mm]

WN+FN are generated by `gnss_lib.noise_from_psd`, whose PSD convention matches
`gnss_lib.whittle_mle` and `gnss_lib.gls_velocity_sigma` exactly; RW is a
kappa=2 power-law process. Everything is seeded.
"""
from __future__ import annotations

import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gnss_lib as gl  # noqa: E402

CYCLE = 2.0 * np.pi


# ---------------------------------------------------------------- signal
def signal_from_spec(t, spec, t0=None):
    t = np.asarray(t, float)
    if t0 is None:
        t0 = float(t[0])
    y = spec["trend"] * (t - t0)
    y = y + spec["A1"] * np.sin(CYCLE * (t - t0) + spec.get("ph1", 0.0))
    y = y + spec["A2"] * np.sin(2 * CYCLE * (t - t0) + spec.get("ph2", 0.7))
    for ep, amp in spec.get("steps", []):
        y = y + amp * (t >= ep)
    for (te, amp, tau) in spec.get("transients", []):
        dt = t - te
        y = y + amp * np.exp(-np.maximum(dt, 0.0) / tau) * (dt >= 0)
    return y


def noise_from_spec(n, spec, dt=gl.DT_YEAR, rng=None):
    rng = rng or np.random.default_rng(0)
    e = gl.noise_from_psd(n, spec.get("S_wn", 0.0), spec.get("S_fn", 0.0), dt, rng)
    rw = spec.get("sigma_rw", 0.0)
    if rw > 0:
        e = e + gl.powerlaw_noise(n, rw, 2.0, dt, rng)
    return e


def _calibrate(model, sigma, n, dt, rng):
    """Find the PSD amplitude that makes the generated process have std=sigma."""
    unit = 1.0
    x = gl.noise_from_psd(n, unit if model == "wn" else 0.0,
                          unit if model == "fn" else 0.0, dt, rng)
    sd = x.std()
    return unit * (sigma / sd) ** 2 if sd > 0 else unit


def make_spec(sigma_wn, sigma_fn, sigma_rw, n, dt=gl.DT_YEAR, seed=0):
    """Return a noise spec dict with S_wn, S_fn calibrated so the generated
    components have the requested std in mm."""
    rng = np.random.default_rng(seed)
    S_wn = _calibrate("wn", sigma_wn, n, dt, rng) if sigma_wn > 0 else 0.0
    S_fn = _calibrate("fn", sigma_fn, n, dt, rng) if sigma_fn > 0 else 0.0
    return {"S_wn": S_wn, "S_fn": S_fn, "sigma_rw": sigma_rw,
            "sigma_wn": sigma_wn, "sigma_fn": sigma_fn}


def make_series(n=3650, spec=None, noise=None, seed=0, t_start=2000.0, dt=gl.DT_YEAR):
    """Build a synthetic series. Returns dict(t, clean, noisy, mask, spec, noise)."""
    spec = spec or default_signal_spec()
    t = t_start + np.arange(n) * dt
    clean = signal_from_spec(t, spec)
    nspec = noise or make_spec(1.0, 3.0, 0.5, n, dt, seed)
    e = noise_from_spec(n, nspec, dt, np.random.default_rng(seed + 1))
    noisy = clean + e
    return {"t": t, "clean": clean, "noise": e, "noisy": noisy,
            "spec": spec, "nspec": nspec, "seed": seed}


def default_signal_spec():
    return {"trend": 20.0, "A1": 6.0, "A2": 2.0,
            "steps": [], "transients": []}


# ---------------------------------------------------------------- gaps
def apply_gaps(t, gap_lengths_days, n_gaps, rng, dt=gl.DT_YEAR):
    """Return a boolean observed-mask with `n_gaps` contiguous gaps of random
    lengths drawn from `gap_lengths_days`, placed at random epochs (start of
    each gap kept at least a margin from the ends)."""
    n = len(t)
    obs = np.ones(n, bool)
    maxL = max(gap_lengths_days)
    starts = rng.integers(10, max(11, n - maxL - 10), size=n_gaps)
    for s in starts:
        L = int(rng.choice(gap_lengths_days))
        obs[s:s + L] = False
    return obs


# ---------------------------------------------------------------- metrics
def rmse(a, b, mask=None):
    a = np.asarray(a, float); b = np.asarray(b, float)
    if mask is not None:
        a = a[mask]; b = b[mask]
    return float(np.sqrt(np.mean((a - b) ** 2)))


def harmonic_amp(y, t, t0=None, k=1):
    if t0 is None:
        t0 = float(np.mean(t))
    X = np.column_stack([np.ones_like(t), t - t0,
                         np.sin(CYCLE * k * (t - t0)), np.cos(CYCLE * k * (t - t0))])
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    return float(np.hypot(beta[2], beta[3]))


def detrended(y, t):
    X = np.column_stack([np.ones_like(t), t - np.mean(t)])
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    return y - X @ beta
